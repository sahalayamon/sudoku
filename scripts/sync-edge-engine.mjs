/**
 * Copies the puzzle engine into the Supabase edge function workspace.
 *
 * The engine has no dependencies and uses only erasable TypeScript, so the very same
 * source runs in the browser, in Node tests and on Deno. Deno needs explicit file
 * extensions on relative imports, which is the only rewrite applied here.
 *
 *   npm run edge:sync
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "src", "lib", "sudoku");
const target = join(root, "supabase", "functions", "_shared", "sudoku");

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });

let count = 0;
for (const file of await readdir(source)) {
  if (!file.endsWith(".ts")) continue;
  const text = await readFile(join(source, file), "utf8");
  const rewritten = text.replace(/(from\s+["'])(\.\/[^"']+?)(["'])/g, (_m, a, spec, c) =>
    spec.endsWith(".ts") ? `${a}${spec}${c}` : `${a}${spec}.ts${c}`,
  );
  await writeFile(join(target, file), `// GENERATED by scripts/sync-edge-engine.mjs from src/lib/sudoku. Do not edit.\n${rewritten}`);
  count++;
}
console.log(`edge:sync copied ${count} engine files to supabase/functions/_shared/sudoku`);
